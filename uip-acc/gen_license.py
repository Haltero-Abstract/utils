#!/usr/bin/env python3
"""Embed LICENSE.md into the accessory as a C array of text lines.

Usage: python3 gen_license.py LICENSE.md src/license_text.h
The full licence text then travels inside UIP.ACC and cannot get lost.
Non-ASCII characters are mapped to the Atari character set (or ASCII),
lines are word-wrapped to LIC_COLS columns.
"""
import sys, textwrap

LIC_COLS = 72

ATARI = {
    '“': '"', '”': '"', '‘': "'", '’': "'",
    '–': '-', '—': '-', '…': '...', ' ': ' ',
    'ł': 'l', 'Ł': 'L', 'ś': 's', 'ń': 'n',
    'é': '\x82', 'è': '\x8a', 'ê': '\x88', 'à': '\x85',
    'ç': '\x87', 'ö': '\x94', 'ü': '\x81', 'ä': '\x84',
    'ß': '\x9e', 'ó': '\xa2', 'á': '\xa0', 'í': '\xa1',
    'ú': '\xa3', '\t': '    ',
}

def to_atari(s):
    out = []
    for ch in s:
        if ch in ATARI:
            out.append(ATARI[ch])
        elif ord(ch) < 128:
            out.append(ch)
        else:
            out.append('?')
    return ''.join(out)

def c_str(s):
    r = []
    for ch in s:
        o = ord(ch)
        if ch == '"': r.append('\\"')
        elif ch == '\\': r.append('\\\\')
        elif 32 <= o < 127: r.append(ch)
        else: r.append('\\%03o' % o)
    return '"' + ''.join(r) + '"'

def main(src, dst):
    text = open(src, encoding='utf-8').read().replace('\r', '')
    lines = []
    for raw in text.split('\n'):
        raw = to_atari(raw.rstrip())
        if len(raw) <= LIC_COLS:
            lines.append(raw)
            continue
        indent = len(raw) - len(raw.lstrip(' '))
        lines.extend(textwrap.wrap(raw, LIC_COLS, subsequent_indent=' ' * indent,
                                   break_long_words=True) or [''])
    with open(dst, 'w') as f:
        f.write('/* Generated by gen_license.py from LICENSE.md - do not edit */\n')
        f.write('#define LIC_COLS %d\n' % LIC_COLS)
        f.write('static const char *const license_text[] = {\n')
        for l in lines:
            f.write('  %s,\n' % c_str(l))
        f.write('};\n#define LICENSE_LINES %d\n' % len(lines))
    print('%d lines -> %s' % (len(lines), dst))

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
